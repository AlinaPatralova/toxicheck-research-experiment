export const ingredientById = researchIngredients.reduce<Record<string, ResearchIngredient>>(
  (map, ingredient) => {
    map[ingredient.id] = ingredient;
    return map;
  },
  {}
);

export function getIngredientOrFallback(id: string): ResearchIngredient {
  return ingredientById[id] || {
    id,
    code: id,
    name: id,
    categoryId: 'unknown',
    categoryName: 'Ингредиенты',
    description: '',
    keywords: []
  };
}

export function getIngredientsByIds(ids: string[]): ResearchIngredient[] {
  return ids.map((id) => getIngredientOrFallback(id));
}
